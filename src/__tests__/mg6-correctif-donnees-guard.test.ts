/** Répertoires racines à parcourir pour la règle (b), au sens de la mission MG.6. */
const SCAN_ROOTS = ["scripts", "prisma"];

/** Extensions concernées par la règle (b) — .sql et .sh uniquement (ADR-049/050). */
const RELEVANT_EXTENSIONS = [".sql", ".sh"];

/** Parcourt récursivement un dossier et retourne les chemins relatifs au repo. */
function listFilesRecursive(absDir: string): string[] {
  if (!existsSync(absDir)) return [];
  const out: string[] = [];
  for (const entry of readdirSync(absDir, { withFileTypes: true })) {
    const abs = path.join(absDir, entry.name);
    if (entry.isDirectory()) {
      out.push(...listFilesRecursive(abs));
    } else if (entry.isFile()) {
      out.push(path.relative(REPO_ROOT, abs));
    }
  }
  return out;
}

/**
 * Classifie un fichier .sql/.sh candidat à la règle (b). Fonction pure (ne
 * lit aucun fichier réel) — testable sur des chemins fabriqués.
 */
export function classifyDataFixCandidate(
  relPath: string
): "migration" | "audit" | "known-non-datafix" | "debt" | "violation" {
  if (isLegitimateMigrationFile(relPath)) return "migration";
  if (isQualifiedAuditPath(relPath)) return "audit";
  if (KNOWN_NON_DATAFIX_FILES.has(relPath)) return "known-non-datafix";
  if (relPath in HISTORICAL_DEBT_EXCLUSIONS) return "debt";
  return "violation";
}

