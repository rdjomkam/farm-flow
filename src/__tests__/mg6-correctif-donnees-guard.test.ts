/**
 * Garde-fou anti-récidive — Story MG.6 (ADR-049 / ADR-050).
 *
 * Contexte : quatre correctifs de données de production ont été commités à la
 * RACINE de `prisma/migrations/` (commit `c259b48`) — `fix-vague2601-phantom-fish.sql`,
 * `fix-bes033-cmd015-duplicate.sql`, `fix-calibrage-may14-missing-biometrie.sql`,
 * `fix-vte004-missing-vagueid.sql`. Prisma ne lit comme migration que les
 * SOUS-DOSSIERS de `prisma/migrations/` contenant un `migration.sql` — ces
 * quatre fichiers étaient donc totalement INERTES : jamais exécutés par
 * `migrate deploy`, jamais enregistrés dans `_prisma_migrations`, sans aucune
 * garantie sur leur application réelle en production (voir ADR-049 §1).
 *
 * Ce fichier verrouille deux invariants distincts :
 *
 *   (a) Aucun fichier ne doit jamais réapparaître à la racine de
 *       `prisma/migrations/` (le bug exact de commit `c259b48`) — vérification
 *       structurelle triviale, sans ambiguïté possible.
 *   (b) Aucun correctif de données à écriture ne doit être ajouté sous forme
 *       de script `.sql`/`.sh` hors du mécanisme de migration — il ne peut
 *       s'agir que d'un audit en lecture seule (ADR-050 : emplacement
 *       `scripts/audits/` + convention de nommage `*-audit-*`).
 *
 * Choix de mécanisme pour (b) — DÉLIBÉRÉMENT PAS une heuristique de mots-clés
 * SQL naïve. La pré-analyse (section F) et ADR-049 §4 rejettent explicitement
 * une détection par regex de contenu (`UPDATE`/`INSERT`/`DELETE` en clair) car
 * un commentaire mentionnant le mot "UPDATE" ne fait pas d'un fichier un
 * correctif, et l'absence de ces mots-clés ne prouve pas qu'un fichier est un
 * audit. Le critère RETENU est donc, par ordre de priorité :
 *   1. Propriété de CHEMIN + NOMMAGE (ADR-050) : un fichier n'est un audit
 *      légitime QUE s'il vit sous `scripts/audits/` ET porte `-audit-` dans
 *      son nom. C'est une propriété du système de fichiers, déterministe,
 *      jamais devinatoire.
 *   2. Pour les fichiers déclarés "audit" par (1), une détection de mots-clés
 *      d'écriture SQL (UPDATE/INSERT/DELETE/ALTER/DROP/TRUNCATE) est utilisée
 *      UNIQUEMENT comme signal de COHÉRENCE (pas comme critère de
 *      qualification) — et seulement HORS des commentaires SQL (`--` et
 *      `/* *\/`), pour éviter un faux positif sur un commentaire qui
 *      mentionnerait ces mots (cf. prose ci-dessus). Si ce signal se
 *      déclenche, il indique une INCOHÉRENCE entre le nommage et le contenu
 *      réel — qui doit être investiguée, pas un verdict automatique de rejet
 *      du fichier par le mécanisme (1).
 *   3. Tout fichier `.sql`/`.sh` sous `scripts/` ou `prisma/` qui n'est ni une
 *      migration légitime (`prisma/migrations/<dossier>/migration.sql`) ni un
 *      audit qualifié par (1) est une VIOLATION — sauf s'il figure dans la
 *      liste de dette historique explicite ci-dessous.
 *
 * Dette historique tolérée (voir détail et justification individuelle plus
 * bas) : neuf fichiers de correctif orphelins antérieurs à ADR-049, dont
 * l'état d'application réel en production est inconnu — on ne les convertit
 * PAS à l'aveugle (MG.3 ne couvre que les 5 correctifs nommément analysés par
 * MG.2 : vague2601, bes033/cmd015, calibrage-may14, vte004, gd3 — tous les 5
 * ont déjà été convertis en migrations, cf. `prisma/migrations/20260727090001..006`).
 * Cette liste est fermée : toute NOUVELLE violation qui n'y figure pas fait
 * échouer le test.
 */

