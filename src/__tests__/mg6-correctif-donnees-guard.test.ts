/**
 * Seule exception légitime : `migration_lock.toml` est déposé par Prisma
 * lui-même (pas par un agent humain) pour verrouiller le provider de
 * datasource ("Please do not edit this file manually" — commentaire généré
 * par Prisma en tête du fichier). Ce n'est pas un correctif de données, pas
 * un script exécutable, et Prisma le régénère de toute façon s'il est
 * supprimé — l'exclure ici ne rouvre aucune porte au bug de commit `c259b48`.
 */
const MIGRATION_LOCK_FILE = "migration_lock.toml";

/** Fonction pure — extraite pour être testable sur des Dirent fabriqués. */
export function findIllegalFilesAtMigrationsRoot(
  entries: Array<Pick<Dirent, "name"> & { isFile(): boolean }>
): string[] {
  return entries
    .filter((e) => e.isFile() && e.name !== MIGRATION_LOCK_FILE)
    .map((e) => e.name);
}

